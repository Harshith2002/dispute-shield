"""Reproduce every number in APPROACH.md: model comparison, final models, what-if, app data.

Usage (from backend/):  python train.py [--data ../data] [--boot 200]
"""
import argparse
import json
import time

import joblib
import numpy as np
import pandas as pd

from config import ARTIFACTS, DATA_DIR, DATA_END, DATA_START, DISPUTE_FEE, EXPERIMENTS, MATURITY_DAYS, VALID_START
from data import load_training
from evidence import EVIDENCE_RULES
from features import History, build_dispute_frame, build_payment_frame, feature_lists
from models import candidates, choose, metrics, top_coefficients
from reasons import label as reason_label
from scoring import Scorer
import whatif

MIN_USEFUL_AUC = 0.55   # below this a column is exported blank: no better than a constant
TARGETS = {
    "risk": ("payment", "Will this payment be disputed? (payment collected)"),
    "win_invoice": ("invoice", "Win chance if disputed, from the invoice only (invoice ready)"),
    "win_payment": ("payment", "Win chance if disputed, invoice + payment (payment collected)"),
    "win_dispute": ("dispute", "Win chance with the evidence submitted (dispute received)"),
}
EXPORT_COLUMN = {"risk": "dispute_risk_score", "win_invoice": "invoice_win_prob",
                 "win_payment": "payment_win_prob", "win_dispute": "win_prob"}


def log(msg):
    print(time.strftime("%H:%M:%S"), msg, flush=True)


def datasets(P, D):
    """Rows, labels and time split per target. Validation = Jan-May 2026 (latest period with mature labels)."""
    mature = (P.collected_at >= DATA_START) & (P.collected_at < DATA_END - pd.Timedelta(days=MATURITY_DAYS))
    R = P[mature]
    decided = D[D.outcome.isin(["won", "lost"]) & D.matched_payment]
    out = {"risk": (R, R.disputed.values, (R.collected_at < VALID_START).values)}
    for t in ["win_invoice", "win_payment", "win_dispute"]:
        out[t] = (decided, (decided.outcome == "won").values.astype(float), (decided.opened_at < VALID_START).values)
    return out


def compare(P, D, flists):
    results, chosen, final = {}, {}, {}
    for target, (fset, question) in TARGETS.items():
        X, y, is_train = datasets(P, D)[target]
        log(f"{target}: train {is_train.sum()} rows, valid {(~is_train).sum()} rows, positives {int(y.sum())}")
        res = {}
        for name, model in candidates(target, flists[fset]).items():
            model.fit(X[is_train], y[is_train])
            res[name] = metrics(y[~is_train], model.predict_proba(X[~is_train])[:, 1])
            log(f"  {name:7s} auc={res[name]['auc']:.3f} logloss={res[name]['log_loss']:.4f} ece={res[name]['ece']:.4f}")
        pick = choose(res)
        if target == "risk":   # tier quality on held-out months, thresholds from training-period scores
            m = candidates(target, flists[fset])[pick].fit(X[is_train], y[is_train])
            lo, hi = np.quantile(m.predict_proba(X[is_train])[:, 1], [0.75, 0.95])
            pv = m.predict_proba(X[~is_train])[:, 1]
            tier = np.where(pv >= hi, "high", np.where(pv >= lo, "medium", "low"))
            vt = pd.DataFrame({"tier": tier, "y": y[~is_train]}).groupby("tier").y.agg(["mean", "size"])
            res[pick]["valid_tiers"] = {t: {"dispute_rate": round(float(r["mean"]), 4), "n": int(r["size"])}
                                        for t, r in vt.iterrows()}
            log(f"  held-out dispute rate by tier: {res[pick]['valid_tiers']}")
        final[target] = candidates(target, flists[fset])[pick].fit(X, y)   # refit on all mature rows
        # reference: predict the training base rate for everyone
        const = metrics(y[~is_train], np.full((~is_train).sum(), y[is_train].mean()))
        log(f"  constant logloss={const['log_loss']:.4f}  (train rate {y[is_train].mean():.4f}, "
            f"valid rate {y[~is_train].mean():.4f})")
        results[target] = {"question": question, "features": fset, "approaches": res, "constant": const}
        chosen[target] = pick
    return results, chosen, final


def write_experiments(results, chosen, blank, coefs):
    EXPERIMENTS.mkdir(exist_ok=True)
    why = {"lookup": "Readable table, but coarse segments", "logreg": "Calibrated and explainable per feature",
           "logreg_small": "Three to five terms: evidence count, team response and win history",
           "gbm": "Captures interactions; harder to explain"}
    lines = ["# Model comparison", "",
             "Generated by `python train.py`. Validation: train on months before Jan 2026, validate on "
             "Jan-May 2026 (risk: payments with a full 90-day dispute window; win models: disputes opened then "
             "and closed won/lost). Selection: lowest validation log loss; within 1% prefer the more explainable "
             "approach (lookup > logreg > gbm). Chosen model is refit on all mature data.", ""]
    for target, r in results.items():
        lines += [f"## {target}: {r['question']}", "",
                  "| approach | AUC | avg precision | log loss | Brier | ECE (calibration) | pred/actual | explainability | decision |",
                  "|---|---|---|---|---|---|---|---|---|"]
        for name, m in r["approaches"].items():
            decision = "**chosen**" if name == chosen[target] else "rejected"
            lines.append(f"| {name} | {m['auc']:.3f} | {m['avg_precision']:.3f} | {m['log_loss']:.4f} | "
                         f"{m['brier']:.4f} | {m['ece']:.4f} | {m['pred_over_actual']:.2f} | {why[name]} | {decision} |")
        c = r["constant"]
        lines.append(f"| constant (reference) | 0.500 | {c['avg_precision']:.3f} | {c['log_loss']:.4f} | "
                     f"{c['brier']:.4f} | {c['ece']:.4f} | {c['pred_over_actual']:.2f} | trivial | reference only |")
        n = r["approaches"][chosen[target]]
        lines += ["", f"Validation rows: {n['n']}, positives: {n['positives']}."]
        if EXPORT_COLUMN[target] in blank:
            lines.append(f"**Exported blank**: AUC below {MIN_USEFUL_AUC} or log loss no better than the constant.")
        if target in coefs:
            lines += ["", "Largest standardised coefficients (refit logistic regression): " +
                      ", ".join(f"`{f}` {c:+.2f}" for f, c in coefs[target])]
        lines.append("")
    (EXPERIMENTS / "results.md").write_text("\n".join(lines), encoding="utf-8")
    (EXPERIMENTS / "results.json").write_text(json.dumps({"results": results, "chosen": chosen, "blank": blank},
                                                         indent=2, default=float), encoding="utf-8")


def outcome_counts(df):
    o = df.outcome.value_counts()
    won, lost = int(o.get("won", 0)), int(o.get("lost", 0))
    return {"disputes": int(len(df)), "won": won, "lost": lost, "withdrawn": int(o.get("withdrawn", 0)),
            "open": int(o.get("open", 0)), "win_rate": round(won / (won + lost), 3) if won + lost else None,
            "usd_lost": round(float(df.loc[df.outcome == "lost", "amount_usd"].sum() + DISPUTE_FEE * lost), 2),
            "responded_rate": round(float(df.merchant_responded.mean()), 3) if len(df) else None}


def app_data(P, D, scorer, teams):
    """Months 1-22 summaries the app shows without any upload."""
    by_reason = []
    for reason, g in D.groupby("reason"):
        by_reason.append({"reason": reason, "label": reason_label(reason), **outcome_counts(g),
                          "avg_amount": round(float(g.amount_usd.mean()), 2)})
    by_reason.sort(key=lambda r: -r["usd_lost"])

    # Gaps: for each fixable evidence item, win-chance points the team would gain (within-team model).
    gap_cols = {}
    for rule in EVIDENCE_RULES:
        if rule.fixable_at and rule.feature in P:
            missing, lift = scorer.evidence_lift(P, rule)
            gap_cols[rule.item] = (rule, missing, lift)
    platform = {item: float(m.mean()) for item, (_, m, _) in gap_cols.items()}

    team_rows = {}
    Pg = P.groupby("team_id").indices
    Dg = dict(list(D.groupby("team_id")))
    for _, t in teams.iterrows():
        idx = Pg.get(t.team_id, np.array([], dtype=int))
        tp = P.iloc[idx]
        td = Dg.get(t.team_id, D.iloc[:0])
        gaps = []
        for item, (rule, missing, lift) in gap_cols.items():
            if len(idx) == 0:
                continue
            share = float(missing[idx].mean())
            gain = float(lift[idx].sum() / len(idx))
            if share > 0 and gain > 0.002:
                gaps.append({"item": item, "label": rule.label, "fix": rule.fix, "share_missing": round(share, 3),
                             "platform_missing": round(platform[item], 3), "win_points_gain": round(gain * 100, 1)})
        gaps.sort(key=lambda g: -g["win_points_gain"])
        recent = td.sort_values("opened_at", ascending=False).head(25)
        team_rows[t.team_id] = {
            "team_id": t.team_id, "profession": t.profession, "state": t.state, "team_size": int(t.team_size),
            "onboarded_on": str(t.onboarded_on.date()) if pd.notna(t.onboarded_on) else None,
            "payments": int(len(tp)), "volume_usd": round(float(tp.amount_usd.sum()), 2),
            "keyed_share": round(float(tp.m_keyed.mean()), 3) if len(tp) else None,
            "dispute_rate": round(len(td) / max(len(tp), 1), 4), **outcome_counts(td),
            "by_reason": [{"reason": r, "label": reason_label(r), **outcome_counts(g)} for r, g in td.groupby("reason")],
            "gaps": gaps[:4],
            "recent_disputes": [{"dispute_id": r.dispute_id, "opened_at": str(r.opened_at.date()),
                                 "reason": reason_label(r.reason), "amount_usd": r.amount_usd, "outcome": r.outcome,
                                 "responded": bool(r.merchant_responded), "evidence": r.evidence_submitted or ""}
                                for r in recent.itertuples()],
        }
    totals = {"payments": int(len(P)), **outcome_counts(D), "dispute_rate": round(len(D) / len(P), 4),
              "platform_keyed_share": round(float(P.m_keyed.mean()), 3)}
    return {"totals": totals, "by_reason": by_reason, "teams": team_rows}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default=str(DATA_DIR))
    ap.add_argument("--boot", type=int, default=200, help="team bootstrap draws for what-if ranges")
    args = ap.parse_args()
    np.random.seed(0)

    log("loading data")
    T = load_training(args.data)
    h = History.from_tables(T)
    log("building as-of features")
    P = build_payment_frame(T["invoices"], T["photos"], T["payments"], h)
    P["disputed"] = P.payment_id.isin(T["disputes"].payment_id).astype(float)
    D = build_dispute_frame(T["disputes"], P)
    flists = feature_lists(h)

    results, chosen, final = compare(P, D, flists)
    blank = [EXPORT_COLUMN[t] for t, r in results.items()
             if r["approaches"][chosen[t]]["auc"] < MIN_USEFUL_AUC
             or r["approaches"][chosen[t]]["log_loss"] >= r["constant"]["log_loss"]]
    coefs = {t: top_coefficients(m) for t, m in final.items() if chosen[t].startswith("logreg")}

    R = datasets(P, D)["risk"][0]
    risk_scores = final["risk"].predict_proba(R)[:, 1]
    tiers = [float(np.quantile(risk_scores, 0.75)), float(np.quantile(risk_scores, 0.95))]
    log(f"what-if: fitting policy models + {args.boot} bootstrap draws")
    wi = whatif.run(P, T["disputes"], n_boot=args.boot, log=log)
    action = wi.pop("action")
    ARTIFACTS.mkdir(exist_ok=True)
    pd.DataFrame(wi["rows"]).to_csv(ARTIFACTS / "whatif_results.csv", index=False)
    (EXPERIMENTS / "whatif.json").write_text(json.dumps(wi, indent=2, default=float), encoding="utf-8")

    bundle = {"models": final, "chosen": chosen, "history": h, "features": flists, "tier_thresholds": tiers,
              "blank": blank, "action": action, "trained_through": str(DATA_END.date())}
    joblib.dump(bundle, ARTIFACTS / "models.joblib", compress=3)
    write_experiments(results, chosen, blank, coefs)
    log(f"models saved; chosen={chosen}; blank={blank}; tiers={tiers}")

    rt = pd.Series(np.where(risk_scores >= tiers[1], "high", np.where(risk_scores >= tiers[0], "medium", "low")))
    tier_check = pd.DataFrame({"tier": rt, "y": R.disputed.values}).groupby("tier").y.agg(["mean", "size"])
    log(f"dispute rate by tier (in-sample):\n{tier_check}")

    log("app data")
    scorer = Scorer(bundle)
    app = app_data(P, D, scorer, T["teams"])
    app["whatif"] = wi
    app["models"] = {"chosen": chosen, "blank": blank, "tier_thresholds": tiers,
                     "validation": {t: r["approaches"][chosen[t]] for t, r in results.items()}}
    (ARTIFACTS / "app_data.json").write_text(json.dumps(app, default=float), encoding="utf-8")
    log("done")


if __name__ == "__main__":
    main()
